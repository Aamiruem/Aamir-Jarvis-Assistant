"""Builds src/data/worldDots.js: a land/sea grid for the Cyber Ops global network map.

Input: Natural Earth 110m land as TopoJSON (the public-domain `world-atlas` npm package,
https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json). Output: one hex bitmask per latitude
row, so the app ships ~3 KB instead of the 55 KB shape file and needs no map service at runtime.

    python -I scripts/gen_world_dots.py path/to/land-110m.json src/data/worldDots.js
"""
import json
import sys

import numpy as np

STEP = 2.0  # degrees per dot
LAT_TOP, LAT_BOTTOM = 84.0, -58.0  # Antarctica left out: nothing there talks to a PC


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        a = np.cumsum(np.array(arc, dtype=float), axis=0)
        arcs.append(np.column_stack([a[:, 0] * sx + tx, a[:, 1] * sy + ty]))
    return arcs


def ring(arcs, idx):
    pts = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a[1:] if pts else a)
    return np.array(pts)


def inside(px, py, poly):
    """Even-odd rule for many points against one ring (vectorised ray casting)."""
    x, y = poly[:, 0], poly[:, 1]
    x2, y2 = np.roll(x, -1), np.roll(y, -1)
    res = np.zeros(px.shape, dtype=bool)
    for xa, ya, xb, yb in zip(x, y, x2, y2):
        cross = (ya > py) != (yb > py)
        with np.errstate(divide="ignore", invalid="ignore"):
            xint = (xb - xa) * (py - ya) / (yb - ya) + xa
        res ^= cross & (px < xint)
    return res


def main(src, dst):
    topo = json.load(open(src, encoding="utf-8"))
    arcs = decode_arcs(topo)
    lons = np.arange(-180 + STEP / 2, 180, STEP)
    lats = np.arange(LAT_TOP - STEP / 2, LAT_BOTTOM, -STEP)
    gx, gy = np.meshgrid(lons, lats)
    land = np.zeros(gx.shape, dtype=bool)
    for geom in topo["objects"]["land"]["geometries"]:
        polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
        for poly in polys:
            hit = np.zeros(gx.shape, dtype=bool)
            for r in (ring(arcs, r) for r in poly):
                if np.any(np.abs(np.diff(r[:, 0])) > 180):  # jumps across the antimeridian: make it continuous
                    r = np.column_stack([np.unwrap(r[:, 0], period=360), r[:, 1]])
                    hit ^= inside(gx, gy, r) | inside(gx + 360, gy, r) | inside(gx - 360, gy, r)
                else:
                    hit ^= inside(gx, gy, r)
            land |= hit
    rows = []
    for row in land:
        bits = "".join("1" if b else "0" for b in row)
        bits += "0" * (-len(bits) % 4)
        rows.append("".join(f"{int(bits[i:i + 4], 2):x}" for i in range(0, len(bits), 4)))
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/gen_world_dots.py from Natural Earth 110m land (public domain). Do not edit.\n")
        f.write(f"export const WORLD = {{ step: {STEP}, latTop: {LAT_TOP}, lonLeft: -180, cols: {len(lons)}, rows: [\n")
        f.write(",\n".join(f"  '{r}'" for r in rows))
        f.write("\n] };\n")
    print(f"{int(land.sum())} land dots, {len(rows)} rows x {len(lons)} cols -> {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
