"""Write master-prompt study notes for every CampusX lecture, one Markdown file per lecture.

    python scripts/generate_campusx_notes.py                 # dry run: counts and a cost ceiling, calls nothing
    python scripts/generate_campusx_notes.py --run           # writes the notes (asks for confirmation first)
    python scripts/generate_campusx_notes.py --run --limit 5 # only the first 5 that still need notes

Notes come from each lecture's title, description and chapter list, not from the video: the
video is never downloaded or transcribed. Members-only lectures are skipped unless you pass
--include-members. Notes already on disk are kept, so a stopped run can be resumed.

Output: backend/fastapi-ai/data/campusx-notes/<n>-<slug>.md (one file per lecture).
Needs a working Claude API key (npm run set-key).
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend" / "fastapi-ai"))

COURSE = ROOT / "frontend" / "public" / "courses" / "campusx-dsmp-2022-23" / "course.json"
OUT = ROOT / "backend" / "fastapi-ai" / "data" / "campusx-notes"
MAX_TOKENS_PER_LECTURE = 32_000  # the limit set in app/study_notes.py
PRICE_PER_MILLION_OUTPUT = None  # set this to your model's output price to see a dollar ceiling


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60] or "lecture"


def path_for(lecture: dict) -> Path:
    return OUT / f"{int(lecture['n']):03d}-{slugify(lecture.get('title', ''))}.md"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", action="store_true", help="actually call Claude and write the notes")
    ap.add_argument("--limit", type=int, default=0, help="stop after this many new notes (0 = all)")
    ap.add_argument("--public-only", action="store_true", help="skip members-only lectures (default: cover all 244 by title)")
    args = ap.parse_args()

    course = json.loads(COURSE.read_text(encoding="utf-8"))
    # Every lecture's TITLE is public, so notes can be written on each topic. For members-only
    # lectures only the title is known (no description), and the video is never used either way.
    lectures = [l for l in course["lectures"] if not (args.public_only and l.get("members_only"))]
    pending = [l for l in lectures if not path_for(l).exists()]
    todo = pending[: args.limit] if args.limit else pending

    members = sum(1 for l in lectures if l.get("members_only"))
    print(f"Lectures in the course: {len(course['lectures'])}")
    print(f"Covered now:            {len(lectures)}  ({members} members-only, from the public title only)" + ("" if not args.public_only else "  (--public-only)"))
    print(f"Notes already written:  {len(lectures) - len(pending)}")
    print(f"Notes to write now:     {len(todo)}")
    ceiling = len(todo) * MAX_TOKENS_PER_LECTURE
    print(f"Output-token ceiling:   {ceiling:,} tokens (each note is capped at {MAX_TOKENS_PER_LECTURE:,}; most are shorter)")
    if PRICE_PER_MILLION_OUTPUT:
        print(f"Dollar ceiling:         ${ceiling / 1_000_000 * PRICE_PER_MILLION_OUTPUT:,.2f} (output tokens only)")

    if not args.run:
        print("\nDry run: nothing was sent to Claude. Re-run with --run to write the notes.")
        return 0
    if not todo:
        print("Nothing to do.")
        return 0
    if input(f"\nThis will call Claude {len(todo)} times. Type YES to continue: ").strip() != "YES":
        print("Cancelled.")
        return 1

    from app import study_notes  # imported late, so a dry run doesn't need the AI service's settings

    OUT.mkdir(parents=True, exist_ok=True)
    written = 0
    for lecture in todo:
        target = path_for(lecture)
        print(f"[{lecture['n']}] {lecture.get('title', '')} ...", end=" ", flush=True)
        try:
            result = study_notes.generate(
                topic=lecture.get("title") or f"Lecture {lecture['n']}",
                lecture={
                    "n": lecture["n"],
                    "title": lecture.get("title", ""),
                    "course": course.get("title", "CampusX"),
                    "description": lecture.get("description", ""),
                },
                context="",
                progress=lambda *_: None,
            )
        except ValueError as e:  # bad key, refusal, API trouble: stop rather than burn more calls
            print(f"stopped: {e}")
            return 2
        target.write_text(
            f"<!-- lecture {lecture['n']}: {lecture.get('title', '')} | generated by the master prompt; based on the title and description, not the video -->\n\n"
            + result["markdown"]
            + "\n",
            encoding="utf-8",
        )
        written += 1
        print(f"saved ({result['output_tokens']:,} tokens)")
    print(f"\nDone: {written} written. Files are in {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
